import mongoose from "mongoose";

const eventRegistrationSchema = new mongoose.Schema(
  {
    // ==========================================
    // EVENT AND USER
    // ==========================================

    event: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Event",
      required: true,
      index: true,
    },

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // One registration belongs to exactly one submission.
    submission: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "EventSubmission",
      required: true,
    },

    // ==========================================
    // REGISTRATION DETAILS
    // ==========================================

    fullName: {
      type: String,
      required: true,
      trim: true,
      maxlength: 100,
    },

    email: {
      type: String,
      required: true,
      lowercase: true,
      trim: true,
    },

    phone: {
      type: String,
      trim: true,
      default: "",
    },

    notes: {
      type: String,
      trim: true,
      maxlength: 1000,
      default: "",
    },

    portfolioOrLink: {
      type: String,
      trim: true,
      default: "",
    },

    // ==========================================
    // PAYMENT INFORMATION
    // ==========================================

    paymentStatus: {
      type: String,
      enum: [
        "not_required",
        "pending_verification",
        "verified",
        "rejected",
        "refunded",
      ],
      default: "not_required",
      index: true,
    },

    paymentMethod: {
      type: String,
      enum: [
        "none",
        "esewa",
        "khalti",
        "bank_transfer",
        "card_gateway",
        "cash",
      ],
      default: "none",
    },

    // Normalized transaction reference.
    // Free registrations should leave this field unset.
    paymentReference: {
      type: String,
      trim: true,
      uppercase: true,
      maxlength: 150,
      default: undefined,
    },

    paymentRejectionReason: {
      type: String,
      trim: true,
      default: "",
      maxlength: 1000,
    },

    paymentVerifiedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },

    paymentVerifiedAt: {
      type: Date,
      default: null,
    },

    paymentAdminNotes: {
      type: String,
      trim: true,
      default: "",
      maxlength: 2000,
    },

    amountDue: {
      type: Number,
      required: true,
      min: 0,
      default: 0,
    },

    amountPaid: {
      type: Number,
      default: 0,
      min: 0,
    },

    currency: {
      type: String,
      default: "NPR",
      uppercase: true,
      trim: true,
    },

    // ==========================================
    // REGISTRATION REVIEW STATUS
    // ==========================================

    registrationStatus: {
      type: String,
      enum: [
        "pending_review",
        "confirmed",
        "rejected",
        "waitlist",
        "cancelled",
      ],
      default: "pending_review",
      index: true,
    },

    // Whether this registration currently consumes
    // one event participant slot.
    reservesSeat: {
      type: Boolean,
      default: true,
      index: true,
    },

    // Unique receipt/reference generated by the system.
    registrationNumber: {
      type: String,
      trim: true,
      default: "",
      index: true,
    },

    // ==========================================
    // CANCELLATION
    // ==========================================

    cancelledAt: {
      type: Date,
      default: null,
    },

    cancellationReason: {
      type: String,
      trim: true,
      default: "",
      maxlength: 1000,
    },
  },
  {
    timestamps: true,
  },
);

// ==========================================
// INDEXES
// ==========================================

// One registration per creative submission.
// Partial index supports older registrations that
// may not have a submission field.
eventRegistrationSchema.index(
  { submission: 1 },
  {
    unique: true,
    partialFilterExpression: {
      submission: { $type: "objectId" },
    },
  },
);

// A transaction reference can only be used once
// across all PRATIVA event registrations.
//
// Free registrations must leave paymentReference
// unset, not save an empty string.
eventRegistrationSchema.index(
  { paymentReference: 1 },
  {
    unique: true,
    partialFilterExpression: {
      paymentReference: { $type: "string" },
    },
  },
);

// User's registration history for an event.
eventRegistrationSchema.index({
  event: 1,
  user: 1,
  createdAt: -1,
});

// Efficient event participant and capacity queries.
eventRegistrationSchema.index({
  event: 1,
  registrationStatus: 1,
  reservesSeat: 1,
});

// Admin payment review queue.
eventRegistrationSchema.index({
  paymentStatus: 1,
  createdAt: 1,
});

const EventRegistration = mongoose.model(
  "EventRegistration",
  eventRegistrationSchema,
);

export default EventRegistration;
